// Package bitmap provides an embedded 8×8 pixel bitmap font covering ASCII 0x20–0x7E.
//
// Each glyph is 8 bytes; bit 0 of each byte is the leftmost pixel.
// Scale is determined by the requested size relative to the native 8px height.
package bitmap

import (
	"image"
	"math"

	"avyos.dev/lib/graphics/color"
)

const (
	glyphW = 8
	glyphH = 8
)

// Font is a scalable bitmap font.
type Font struct{}

// New returns a bitmap Font.
func New() *Font { return &Font{} }

func (f *Font) Name() string  { return "Bitmap" }
func (f *Font) Style() string { return "Regular" }

func (f *Font) pixelScale(size float64) float64 {
	s := size / float64(glyphH)
	if s < 1 {
		return 1
	}
	return s
}

func (f *Font) RuneAdvance(_ rune, size float64) float64 {
	return float64(glyphW) * f.pixelScale(size)
}

func (f *Font) LineHeight(size float64) float64 {
	return float64(glyphH) * f.pixelScale(size)
}

// DrawRune renders rune r at pixel position (x,y) into dst using anti-aliased
// coverage sampling. For integer scale factors the output is pixel-perfect; for
// fractional scales (e.g. size=20 → scale=2.5) edge pixels are blended with
// proportional alpha, eliminating hard staircase artifacts.
func (f *Font) DrawRune(r rune, size float64, dst *image.RGBA, x, y float64, col color.Color) {
	if r < 0x20 || r > 0x7E {
		r = '?'
	}
	glyph := glyphs[r-0x20]
	scale := f.pixelScale(size) // float — no truncation
	bounds := dst.Bounds()
	cr, cg, cb, ca := col.RGBA8()
	fca := float64(ca)
	ix, iy := int(x), int(y)

	outW := int(math.Ceil(float64(glyphW) * scale))
	outH := int(math.Ceil(float64(glyphH) * scale))

	for oy := range outH {
		py := iy + oy
		if py < bounds.Min.Y || py >= bounds.Max.Y {
			continue
		}
		// Source y range covered by this output row.
		sy0 := float64(oy) / scale
		sy1 := float64(oy+1) / scale
		isy0, isy1 := int(math.Floor(sy0)), int(math.Ceil(sy1))

		for ox := range outW {
			px := ix + ox
			if px < bounds.Min.X || px >= bounds.Max.X {
				continue
			}
			// Source x range covered by this output column.
			sx0 := float64(ox) / scale
			sx1 := float64(ox+1) / scale
			isx0, isx1 := int(math.Floor(sx0)), int(math.Ceil(sx1))

			// Integrate coverage over [sx0,sx1] × [sy0,sy1].
			var covered float64
			for sy := isy0; sy < isy1 && sy < glyphH; sy++ {
				if sy < 0 {
					continue
				}
				dy := math.Min(sy1, float64(sy+1)) - math.Max(sy0, float64(sy))
				if dy <= 0 {
					continue
				}
				for sx := isx0; sx < isx1 && sx < glyphW; sx++ {
					if sx < 0 || glyph[sy]&(1<<uint(sx)) == 0 {
						continue
					}
					dx := math.Min(sx1, float64(sx+1)) - math.Max(sx0, float64(sx))
					if dx > 0 {
						covered += dx * dy
					}
				}
			}
			totalArea := (sx1 - sx0) * (sy1 - sy0)
			if covered <= 0 || totalArea <= 0 {
				continue
			}

			alpha := covered / totalArea * fca
			if alpha <= 0 {
				continue
			}

			off := dst.PixOffset(px, py)
			// Porter-Duff source-over composite.
			sa := alpha / 255.0
			da := float64(dst.Pix[off+3]) / 255.0
			oa := sa + da*(1-sa)
			if oa <= 0 {
				continue
			}
			fcr, fcg, fcb := float64(cr)/255.0, float64(cg)/255.0, float64(cb)/255.0
			dst.Pix[off+0] = uint8((fcr*sa + float64(dst.Pix[off+0])/255.0*da*(1-sa)) / oa * 255)
			dst.Pix[off+1] = uint8((fcg*sa + float64(dst.Pix[off+1])/255.0*da*(1-sa)) / oa * 255)
			dst.Pix[off+2] = uint8((fcb*sa + float64(dst.Pix[off+2])/255.0*da*(1-sa)) / oa * 255)
			dst.Pix[off+3] = uint8(oa * 255)
		}
	}
}

